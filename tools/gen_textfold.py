"""Generate src/textfold.c: fold UTF-8 text to what the Playdate's Asheville
font can draw (ASCII plus the ellipsis). Accented letters lose their accents,
typographic punctuation becomes ASCII, anything else is dropped."""
import unicodedata
special = {0xC6: "AE", 0xE6: "ae", 0xDF: "ss", 0x152: "OE", 0x153: "oe", 0xD8: "O", 0xF8: "o",
           0x141: "L", 0x142: "l", 0xD0: "D", 0xF0: "d", 0xDE: "Th", 0xFE: "th", 0x110: "D", 0x111: "d",
           0xA0: " ", 0xAB: '"', 0xBB: '"', 0xB7: "-", 0xA9: "(c)", 0xAE: "(R)", 0xB0: "", 0xD7: "x", 0xF7: "/",
           0xA3: "GBP ", 0xBF: "", 0xA1: "", 0xBD: "1/2", 0xBC: "1/4", 0xBE: "3/4"}
table = []
for cp in range(0xA0, 0x250):
    if cp in special: s = special[cp]
    else:
        d = unicodedata.normalize("NFKD", chr(cp))
        s = "".join(c for c in d if ord(c) < 0x80 and not unicodedata.combining(c))
    table.append(s)
punct = {0x2010: "-", 0x2011: "-", 0x2012: "-", 0x2013: "-", 0x2014: "-", 0x2015: "-", 0x2212: "-",
         0x2018: "'", 0x2019: "'", 0x201A: "'", 0x201B: "'", 0x2032: "'", 0x02BC: "'",
         0x201C: '"', 0x201D: '"', 0x201E: '"', 0x201F: '"', 0x2033: '"',
         0x2022: "*", 0x2026: "…", 0x20AC: "EUR ", 0x2122: "TM", 0x2009: " ", 0x202F: " ", 0x2002: " ", 0x2003: " "}
def cstr(s):
    out = ""
    for ch in s:
        if ch == "\\": out += "\\\\"
        elif ch == '"': out += '\\"'
        elif 32 <= ord(ch) < 127: out += ch
        else: out += "".join("\\x%02X" % b for b in ch.encode("utf-8"))
    return '"' + out + '"'
with open("src/textfold.c", "w") as f:
    f.write("/* Generated by tools/gen_textfold.py. */\n#include <stdint.h>\n#include <string.h>\n\n")
    f.write("static const char *const k_latin[%d] = {\n" % len(table))
    for i in range(0, len(table), 12):
        f.write("    " + ", ".join(cstr(s) for s in table[i:i+12]) + ",\n")
    f.write("};\n\n")
    f.write("static const char *punct(uint32_t cp) {\n    switch (cp) {\n")
    for cp, s in punct.items():
        lit = '"\\xE2\\x80\\xA6"' if s == "…" else cstr(s)
        f.write("    case 0x%04X: return %s;\n" % (cp, lit))
    f.write("    }\n    return \"\";\n}\n\n")
    f.write('''/* Fold UTF-8 `in` into `out` (always NUL-terminated). */
void text_fold(const char *in, char *out, int cap) {
    int o = 0;
    const unsigned char *p = (const unsigned char *)in;
    while (*p && o < cap - 4) {
        uint32_t cp; int n;
        if (*p < 0x80) { cp = *p; n = 1; }
        else if ((*p & 0xE0) == 0xC0 && p[1]) { cp = (uint32_t)(*p & 0x1F) << 6 | (p[1] & 0x3F); n = 2; }
        else if ((*p & 0xF0) == 0xE0 && p[1] && p[2]) { cp = (uint32_t)(*p & 0x0F) << 12 | (uint32_t)(p[1] & 0x3F) << 6 | (p[2] & 0x3F); n = 3; }
        else if ((*p & 0xF8) == 0xF0 && p[1] && p[2] && p[3]) { cp = 0x10000; n = 4; }
        else { p++; continue; }
        const char *s;
        char one[2];
        if (cp < 0x80) { one[0] = (char)cp; one[1] = 0; s = one; }
        else if (cp >= 0xA0 && cp < 0x250) s = k_latin[cp - 0xA0];
        else s = punct(cp);
        size_t l = strlen(s);
        if (o + (int)l >= cap - 1) break;
        memcpy(out + o, s, l); o += (int)l;
        p += n;
    }
    out[o] = 0;
}
''')
print("ok")
