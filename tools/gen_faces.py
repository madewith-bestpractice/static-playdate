"""Generate src/faces.h: the phone's 11 daily listener faces (Material Symbols,
Apache 2.0, from static-chumby/src/icons.h) as 26x26 1-bit row masks."""
import re, sys
src = open(sys.argv[1]).read()
names = re.search(r"icon_faces\[11\] = \{([^}]*)\}", src).group(1).replace("&", "").replace(" ", "").split(",")
out = ["/* Generated by tools/gen_faces.py from the Chumby port's icons (Material", " * Symbols, Apache 2.0). The phone's daily listener faces, 26x26, bit 25 = left. */",
       "#pragma once", "#include <stdint.h>", "", "static const uint32_t k_faces[11][26] = {"]
for n in names:
    bits = re.search(r"%s_bits\[676\] = \{([^}]*)\}" % n, src).group(1)
    a = [int(x, 0) for x in bits.replace("\n", "").split(",") if x.strip()]
    rows = []
    for y in range(26):
        m = 0
        for x in range(26):
            if a[y * 26 + x] >= 110: m |= 1 << (25 - x)
        rows.append("0x%07x" % m)
    out.append("    { " + ", ".join(rows) + " },")
out.append("};")
open("src/faces.h", "w").write("\n".join(out) + "\n")
print(len(names), "faces")
